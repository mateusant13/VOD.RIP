$md += '  unsure/                 merged-or-not but DIRTY, or state not established'
$md += '  done/                   proven merged into main AND a clean tree'
$md += '  archive/                genuinely abandoned, reason recorded'
$md += '```'
$md += ''
$md += 'The four state names are **verified**, not assumed: they come from'
$md += '`wtroot_states` in `scripts/lib/worktree-roots.sh` (ported verbatim from'
$md += '`I:\!manager\scripts\lib\worktree-roots.sh`).'
$md += ''
$md += '### Why `I:` and not `G:` or `H:`'
$md += ''
$md += '`git worktree move` is **same-drive-only**. All 42 registered VOD.RIP worktrees'
$md += 'were on `I:`. A root on `G:` or `H:` would not merely be slower - it would make'
$md += 'the whole migration impossible, because git refuses a cross-drive move outright.'
$md += 'So the root shares `I:` with the trees being moved. `archive/` is a sibling of'
$md += 'the other three states, so it is on the same drive as the root for free, which is'
$md += 'the entire reason that state exists.'
$md += ''
$md += "Free space, measured now: C: $($free['C:']) GB - G: $($free['G:']) GB - H: $($free['H:']) GB - I: $($free['I:']) GB."
$md += ''
$md += '### This moved nothing across drives, so it freed no space'
$md += ''
$md += "**Bytes reclaimed: 0.** The $([math]::Round($totalB/1MB)) MB measured across these lanes"
