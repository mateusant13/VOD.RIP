# Measures the post-migration inventory and WRITES docs/worktree-topology.md.
# Every number in the output comes from a measurement taken here.
#
#   .\scripts\wt-inventory.ps1              reuse the cached measurement if present
#   .\scripts\wt-inventory.ps1 -ReMeasure   re-walk every worktree (minutes)
#
# The cache exists because a full byte measurement of 42 worktrees takes minutes and
# the RESULT (which lane is where, which state, how big) does not change between two
# runs minutes apart. -ReMeasure when you want the bytes re-read from disk.
param([switch]$ReMeasure)
$ErrorActionPreference = 'Continue'
$td   = Get-Content 'G:\Temp\wt-topology-current-tmpdir.txt'
$repo = 'C:\Users\Administrador\Desktop\Nova pasta (3)\TESTE\VOD.RIP'
$w    = 'I:\vod-rip-wt\wip\wt-topology'
Set-Location $w

$class = @{}
foreach ($r in (Import-Csv (Join-Path $td 'classify2.csv'))) { $class[$r.leaf] = $r }
$outcome = @{}
foreach ($l in (Get-Content (Join-Path $td 'migration\migration.tsv') | Where-Object { $_ -notmatch '^lane' })) {
  $f = $l -split "`t"; $outcome[$f[0]] = $f[4]
}
$loc = @{}
foreach ($l in (git -C $repo worktree list --porcelain | Select-String '^worktree ')) {
  $p = ($l -replace '^worktree ','').TrimEnd('/'); $loc[(Split-Path $p -Leaf)] = $p
}

$cache = Join-Path $td 'final-inventory.csv'
if ((Test-Path $cache) -and (-not $ReMeasure)) {
  "reusing cached measurement ($cache) - pass -ReMeasure to re-walk the trees"
  $rows = Import-Csv $cache
} else {
  "measuring bytes..."
  $rows = @()
  foreach ($leaf in ($class.Keys | Sort-Object)) {
    $c = $class[$leaf]
    $p = if ($loc.ContainsKey($leaf)) { $loc[$leaf] } else { $null }
    $bytes = 0
    if ($p -and (Test-Path -LiteralPath $p)) {
      $m = Get-ChildItem -LiteralPath $p -Force -Recurse -File -ErrorAction SilentlyContinue |
           Measure-Object -Property Length -Sum
      $bytes = [int64]$m.Sum
    }
    $rows += [pscustomobject]@{
      lane=$leaf; path=$p; branch=$c.branch; merged=$c.merged; ahead=$c.ahead
      dirty=$c.dirty; state=$c.state; junction=($c.junction -eq 'True')
      bytes=$bytes; outcome=$outcome[$leaf]
    }
  }
  $rows | Export-Csv $cache -NoTypeInformation -Encoding UTF8
}

# NOTE: Get-PSDrive takes the drive NAME, with no colon. Passing 'I:' raises
# "Cannot find drive", and $free[$d] silently became 0, so an earlier run wrote
# "C: 0 GB - G: 0 GB - H: 0 GB - I: 0 GB" into the doc. A measurement that fails
# must not be formatted as if it succeeded.
$free = @{}
foreach ($d in 'C','G','H','I') {
  $drv = Get-PSDrive -Name $d -ErrorAction SilentlyContinue
  if ($drv) { $free["$d`:"] = [math]::Round(($drv.Free/1GB),1) } else { $free["$d`:"] = 'unavailable' }
}

# When $rows came from the CSV cache its `bytes` is a STRING, and Measure-Object
# refuses strings ("the input object is not numeric") - so cast before summing.
# An earlier version of this file hit exactly that and the totals silently came out
# empty; a measurement that cannot be computed must not be printed as if it were.
$bytesOf = { param($set) ($set | ForEach-Object { [int64]$_.bytes } | Measure-Object -Sum).Sum }
$totalB = & $bytesOf $rows
$movB   = & $bytesOf ($rows | Where-Object { $_.junction -ne 'True' })
$juncB  = & $bytesOf ($rows | Where-Object { $_.junction -eq 'True' })
$nMoved   = ($rows | Where-Object { $_.outcome -eq 'MOVED' }).Count
$nAlready = ($rows | Where-Object { $_.outcome -eq 'ALREADY' }).Count
$nRefused = ($rows | Where-Object { $_.outcome -eq 'REFUSED-junction' }).Count
$nDone    = ($rows | Where-Object { $_.state -eq 'done' }).Count
$nUnsure  = ($rows | Where-Object { $_.state -eq 'unsure' }).Count
$nWip     = ($rows | Where-Object { $_.state -eq 'wip' }).Count
$nArch    = ($rows | Where-Object { $_.state -eq 'archive' }).Count
$ledgerRows = (Get-Content 'docs/wt-migration-ledger.tsv' | Where-Object { $_ -notmatch '^#' -and $_.Trim() }).Count
$inspected  = (git -C $repo worktree list --porcelain | Select-String '^worktree I:/vod-rip-wt').Count
$strays     = (git -C $repo worktree list --porcelain | Select-String '^worktree I:/TEMP').Count
$mainSha    = (git -C $repo rev-parse --short main)
$now        = (Get-Date).ToString('yyyy-MM-dd HH:mm zzz')

