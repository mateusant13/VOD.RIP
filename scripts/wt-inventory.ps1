$md += ''
$md += "Classified: **done $nDone, unsure $nUnsure, wip $nWip, archive $nArch** (total $($rows.Count))."
$md += ''
$md += 'Classification rules, applied strictly:'
$md += ''
$md += '- `done` - branch proven merged into `main` (`git branch --merged main` AND'
$md += '  `git log main..<branch>` empty) **and** a clean tree.'
$md += "- ``unsure`` `` - merged or not, but the tree is dirty, or the state could not be"
