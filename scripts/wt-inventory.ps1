$md += "`docs/wt-migration-ledger.tsv`, currently $ledgerRows rows)."
$md += ''
$md += 'Run `bash scripts/wt-new.sh --selftest` after touching the tooling: 27 checks, two'
$md += 'arms (a throwaway fixture repo, then read-only assertions against this manifest).'
$md += ''
