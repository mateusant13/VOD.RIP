// botGate.* and progress.* keys are namespaced (not English sentences), so
// they need explicit English entries — every other key falls back to the key itself.

const DICTS: Record<Lang, Record<string, string>> = { en, 'pt-BR': ptBR, es }

let currentLang: Lang = 'en'
const listeners = new Set<() => void>()

export function getLanguage(): Lang {
  return currentLang
}

export function setLanguage(lang: Lang): void {
  if (lang === currentLang) return
  currentLang = lang
  listeners.forEach((l) => l())
}

/** Look up a string; missing keys fall back to the English source text. */
export function t(key: string, vars?: Vars): string {
  const template = DICTS[currentLang][key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in vars ? String(vars[name]) : m,
  )
}

const subscribe = (l: () => void) => {
  listeners.add(l)
  return () => {
    listeners.delete(l)
  }
}
const getSnapshot = () => currentLang

/** React hook: re-renders the component when the language changes. */
export function useI18n(): { lang: Lang; setLang: (l: Lang) => void; t: typeof t } {
  const lang = useSyncExternalStore(subscribe, getSnapshot)
  const setLang = useCallback((l: Lang) => setLanguage(l), [])
  return useMemo(() => ({ lang, setLang, t }), [lang, setLang])
}
