/**
 * i18n — plain-TS dictionaries (NO new dependency).
 *
 * Design: keys ARE the English source strings, so the `en` dictionary is
 * implicit — a key missing from the current dictionary falls back to the
 * key itself, which IS the English text. This keeps the default render
 * byte-identical (existing tests keep passing) and lets niche strings stay
 * English without dictionary entries.
 *
 * `t()` is a pure function of the module-level language at call time — no
 * stale closures, safe to call from event handlers and non-React code.
 * `useI18n()` re-renders the component on language switches.
 */
import { useCallback, useMemo, useSyncExternalStore } from 'react'

export type Lang = 'en' | 'pt-BR' | 'es'
export type Vars = Record<string, string | number>

/** Effective language family code for transcripts/captions ('pt' | 'es' | 'en'). */
export function langFamily(lang: Lang): 'pt' | 'es' | 'en' {
  return lang === 'pt-BR' ? 'pt' : lang
}

/** Detect the OS/system language: pt → pt-BR, es → es, anything else → en. */
export function detectSystemLanguage(): Lang {
  const raw = (typeof navigator !== 'undefined' ? navigator.language : '') || ''
  const tag = raw.toLowerCase()
  if (tag.startsWith('pt')) return 'pt-BR'
  if (tag.startsWith('es')) return 'es'
  return 'en'
}

